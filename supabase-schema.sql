CREATE TABLE IF NOT EXISTS properties (
  id BIGINT PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  title TEXT NOT NULL,
  price INT NOT NULL,
  rooms INT DEFAULT 1,
  area NUMERIC(6,1),
  floor INT,
  address TEXT,
  description TEXT,
  district TEXT,
  class TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

